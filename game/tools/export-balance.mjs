import { readFileSync, writeFileSync } from 'node:fs';
const config = JSON.parse(readFileSync(new URL('../../shared/config/balance.json', import.meta.url)));
const schema = JSON.parse(readFileSync(new URL('../../shared/config/balance.schema.json', import.meta.url)));
const output = `// Generated by game/tools/export-balance.mjs from JSON. Do not edit.\nexport const BALANCE_TABLE = ${JSON.stringify(config)};\nexport const BALANCE_SCHEMA = ${JSON.stringify(schema)};\n`;
const target = new URL('../../shared/config/generated.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Balance export stale; run npm run config:export');
} else writeFileSync(target, output);
